// Builds the generated CSS from the design tokens in tokens/ (W3C DTCG JSON).
//
//   pnpm tokens          write styles/brand.css and styles/theme.css
//   pnpm tokens --check  exit 1 if those files are out of date (no writes)
//
// tokens/brand.json        brand primitives → styles/brand.css (Tailwind v4 @theme)
// tokens/themes/light.json semantic tokens  → styles/theme.css (:root, [data-theme="light"])
// tokens/themes/dark.json  semantic tokens  → styles/theme.css (.dark, [data-theme="dark"])
//
// Aliases like "{color.navy-900}" resolve to the brand value at build time, so the
// CSS carries literal values (no dependency on which @theme variables Tailwind emits).
// No dependencies on purpose: the naming follows Tailwind v4 (--color-*, --text-*--line-height),
// which a generic token tool would need custom transforms for.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => JSON.parse(readFileSync(join(root, p), "utf8"));

const brand = read("tokens/brand.json");
const light = read("tokens/themes/light.json");
const dark = read("tokens/themes/dark.json");

const isToken = (node) => node && typeof node === "object" && "$value" in node;
const entries = (group) => Object.entries(group).filter(([key]) => !key.startsWith("$"));

function lookup(path) {
  let node = brand;
  for (const part of path.split(".")) {
    node = node?.[part];
  }
  if (!isToken(node)) throw new Error(`Unknown token reference {${path}}`);

  return node.$value;
}

const resolve = (value) =>
  typeof value === "string" ? value.replace(/\{([\w.-]+)\}/g, (_, path) => resolve(lookup(path))) : value;

const comment = (token) => {
  const notes = [token.$description, typeof token.$value === "string" && /^\{.+\}$/.test(token.$value) && !token.$description ? `= ${token.$value.slice(1, -1)}` : null].filter(Boolean);

  return notes.length ? ` /* ${notes.join(" ")} */` : "";
};

const fontValue = (value) =>
  Array.isArray(value) ? value.map((f) => (/\s/.test(f) && !f.startsWith("var(") ? `"${f}"` : f)).join(", ") : value;

function brandCss() {
  const groups = [];
  for (const [group, tokens] of entries(brand)) {
    const lines = [];
    for (const [name, token] of entries(tokens)) {
      const v = token.$value;
      if (token.$type === "typography") {
        lines.push(`  --${group}-${name}: ${resolve(v.fontSize)};${comment(token)}`);
        if (v.lineHeight) lines.push(`  --${group}-${name}--line-height: ${v.lineHeight};`);
        if (v.letterSpacing) lines.push(`  --${group}-${name}--letter-spacing: ${v.letterSpacing};`);
      } else {
        lines.push(`  --${group}-${name}: ${fontValue(resolve(v))};${comment(token)}`);
      }
    }
    groups.push(lines.join("\n"));
  }

  return `${header(BRAND_NOTES)}@theme {\n${groups.join("\n\n")}\n}\n`;
}

function themeBlock(selector, tokens) {
  const lines = entries(tokens).map(([name, token]) => `    --${name}: ${resolve(token.$value)};${comment(token)}`);

  return `  ${selector} {\n${lines.join("\n")}\n  }`;
}

function themeCss() {
  return `${header(THEME_NOTES)}@layer base {\n${themeBlock(':root,\n  [data-theme="light"]', light)}\n\n${themeBlock('.dark,\n  [data-theme="dark"]', dark)}\n}\n`;
}

const header = (notes) =>
  `/*\n * GENERATED by tokens/build.mjs from tokens/*.json. Do not edit this file:\n * change the JSON in tokens/ and run \`pnpm tokens\`. See docs/design/README.md.\n *\n${notes.map((l) => ` *${l ? ` ${l}` : ""}`).join("\n")}\n */\n\n`;

const BRAND_NOTES = [
  "ekklesiaio brand primitives as Tailwind v4 theme variables (bg-navy-900,",
  "text-gold-800, font-display, text-display-xl, rounded-card, shadow-float, ...).",
  "",
  "Not defined here on purpose: --color-muted, --color-surface, --color-danger,",
  "--color-field and --color-subtle. HeroUI already registers those names as",
  "theme-aware utilities (--color-muted: var(--muted)); redefining them would pin",
  "text-muted, bg-surface, etc. to their light values. Their light/dark values",
  "live in tokens/themes/*.json (styles/theme.css).",
  "",
  "Fonts load with next/font in config/fonts.ts as --font-figtree,",
  "--font-newsreader and --font-inter.",
];

const THEME_NOTES = [
  "The ekklesiaio brand mapped onto HeroUI v3's theme variables, light and dark.",
  "HeroUI reads every color from these, and Tailwind exposes them as theme-aware",
  "utilities (bg-surface, text-muted, bg-accent, ...). globals.css imports this",
  "after @heroui/styles, so it wins over HeroUI's defaults.",
];

const outputs = [
  ["styles/brand.css", brandCss()],
  ["styles/theme.css", themeCss()],
];

const check = process.argv.includes("--check");
let stale = 0;
for (const [file, css] of outputs) {
  const path = join(root, file);
  let current = "";
  try {
    current = readFileSync(path, "utf8");
  } catch {}
  if (current === css) continue;
  if (check) {
    stale++;
    console.error(`${file} is out of date. Run \`pnpm tokens\`.`);
  } else {
    writeFileSync(path, css);
    console.log(`wrote ${file}`);
  }
}
if (check && stale) process.exit(1);
if (check) console.log("tokens: generated CSS is up to date");
